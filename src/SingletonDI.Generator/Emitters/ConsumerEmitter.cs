using System.Collections.Immutable;
using System.Text;
using SingletonDI.Generator.Helpers;
using SingletonDI.Generator.Models;

namespace SingletonDI.Generator.Emitters;

internal static class ConsumerEmitter
{
    public static ImmutableDictionary<string, string> Generate(List<ConsumerModel> consumers)
    {
        return Generate(
            consumers,
            ImmutableDictionary<ServiceTypeIdentity, string>.Empty,
            ImmutableDictionary<ServiceTypeIdentity, string?>.Empty);
    }

    public static ImmutableDictionary<string, string> Generate(
        List<ConsumerModel> consumers,
        ImmutableDictionary<string, string> propertyNames,
        ImmutableDictionary<string, string?> customPropertyNames)
    {
        if (consumers.Count == 0)
        {
            return ImmutableDictionary<string, string>.Empty;
        }

        var result = ImmutableDictionary.CreateBuilder<string, string>();

        foreach (var consumer in consumers)
        {
            var source = GenerateConsumerClass(consumer, propertyNames, customPropertyNames);
            var fullyQualifiedName = consumer.FullyQualifiedName.StartsWith(
                "global::",
                StringComparison.Ordinal)
                ? consumer.FullyQualifiedName.Substring("global::".Length)
                : consumer.FullyQualifiedName;
            result[$"{fullyQualifiedName.Replace('.', '_')}.g.cs"] = source;
        }

        return result.ToImmutable();
    }

    public static ImmutableDictionary<string, string> Generate(
        List<ConsumerModel> consumers,
        ImmutableDictionary<ServiceTypeIdentity, string> propertyNames,
        ImmutableDictionary<ServiceTypeIdentity, string?> customPropertyNames)
    {
        if (consumers.Count == 0)
        {
            return ImmutableDictionary<string, string>.Empty;
        }

        var result = ImmutableDictionary.CreateBuilder<string, string>();

        foreach (var consumer in consumers)
        {
            var source = GenerateConsumerClass(consumer, propertyNames, customPropertyNames);
            var fullyQualifiedName = consumer.FullyQualifiedName.StartsWith(
                "global::",
                StringComparison.Ordinal)
                ? consumer.FullyQualifiedName.Substring("global::".Length)
                : consumer.FullyQualifiedName;
            result[$"{fullyQualifiedName.Replace('.', '_')}.g.cs"] = source;
        }

        return result.ToImmutable();
    }

    private static string GenerateConsumerClass(
        ConsumerModel consumer,
        ImmutableDictionary<ServiceTypeIdentity, string> propertyNames,
        ImmutableDictionary<ServiceTypeIdentity, string?> customPropertyNames)
    {
        var consumerPropertyNames = PropertyNameResolver.ResolveConsumerPropertyNamesByIdentity(
            consumer.Dependencies,
            propertyNames,
            customPropertyNames,
            out _);
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine();

        if (!string.IsNullOrEmpty(consumer.Namespace) && consumer.Namespace != "<global namespace>")
        {
            var namespaceName = consumer.Namespace.StartsWith(
                "global::",
                StringComparison.Ordinal)
                ? consumer.Namespace.Substring("global::".Length)
                : consumer.Namespace;
            source.AppendLine($"namespace {namespaceName}");
            source.AppendLine("{");
        }

        source.AppendLine($"    partial class {consumer.ShortName}");
        source.AppendLine("    {");

        foreach (var dependency in consumer.Dependencies)
        {
            var identity = dependency.Identity is { } dependencyIdentity &&
                           !string.IsNullOrEmpty(dependencyIdentity.FullyQualifiedName)
                ? dependencyIdentity
                : new ServiceTypeIdentity(dependency.FullyQualifiedName, string.Empty);
            if (!consumerPropertyNames.TryGetValue(identity, out var propertyName))
            {
                continue;
            }

            var dependencyType = identity.ToGlobalTypeName();
            source.AppendLine("        /// <summary>");
            source.AppendLine($"        /// Gets the singleton instance of {dependencyType}.");
            source.AppendLine("        /// </summary>");
            source.AppendLine($"        private static {dependencyType} {propertyName}");
            source.AppendLine("        {");
            source.AppendLine("            get");
            source.AppendLine("            {");
            source.AppendLine(
                $"                return global::SingletonDI.Generated.__SingletonDIHost__.Resolve<{dependencyType}>();");
            source.AppendLine("            }");
            source.AppendLine("        }");
            source.AppendLine();
        }

        source.AppendLine("    }");

        if (!string.IsNullOrEmpty(consumer.Namespace) && consumer.Namespace != "<global namespace>")
        {
            source.AppendLine("}");
        }

        return source.ToString();
    }

    private static string GenerateConsumerClass(
        ConsumerModel consumer,
        ImmutableDictionary<string, string> propertyNames,
        ImmutableDictionary<string, string?> customPropertyNames)
    {
        var consumerPropertyNames = PropertyNameResolver.ResolveConsumerPropertyNames(
            consumer.Dependencies,
            propertyNames,
            customPropertyNames,
            out _);
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine();

        if (!string.IsNullOrEmpty(consumer.Namespace) && consumer.Namespace != "<global namespace>")
        {
            var namespaceName = consumer.Namespace.StartsWith(
                "global::",
                StringComparison.Ordinal)
                ? consumer.Namespace.Substring("global::".Length)
                : consumer.Namespace;
            source.AppendLine($"namespace {namespaceName}");
            source.AppendLine("{");
        }

        source.AppendLine($"    partial class {consumer.ShortName}");
        source.AppendLine("    {");

        foreach (var dependency in consumer.Dependencies)
        {
            if (!consumerPropertyNames.TryGetValue(dependency.FullyQualifiedName, out var propertyName))
            {
                continue;
            }

            var dependencyType = ToGlobalTypeName(dependency.FullyQualifiedName);
            source.AppendLine("        /// <summary>");
            source.AppendLine($"        /// Gets the singleton instance of {dependencyType}.");
            source.AppendLine("        /// </summary>");
            source.AppendLine($"        private static {dependencyType} {propertyName}");
            source.AppendLine("        {");
            source.AppendLine("            get");
            source.AppendLine("            {");
            source.AppendLine(
                $"                return global::SingletonDI.Generated.__SingletonDIHost__.Resolve<{dependencyType}>();");
            source.AppendLine("            }");
            source.AppendLine("        }");
            source.AppendLine();
        }

        source.AppendLine("    }");

        if (!string.IsNullOrEmpty(consumer.Namespace) && consumer.Namespace != "<global namespace>")
        {
            source.AppendLine("}");
        }

        return source.ToString();
    }

    private static string ToGlobalTypeName(string fullyQualifiedName)
    {
        return fullyQualifiedName.StartsWith("global::", StringComparison.Ordinal)
            ? fullyQualifiedName
            : $"global::{fullyQualifiedName}";
    }
}
