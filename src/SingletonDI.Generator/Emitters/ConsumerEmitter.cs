using System.Collections.Immutable;
using System.Security.Cryptography;
using System.Text;
using SingletonDI.Generator.Helpers;
using SingletonDI.Generator.Models;

namespace SingletonDI.Generator.Emitters;

internal static class ConsumerEmitter
{
    public static ImmutableDictionary<string, string> Generate(List<ConsumerModel> consumers)
    {
        if (consumers.Count == 0)
        {
            return ImmutableDictionary<string, string>.Empty;
        }

        var result = ImmutableDictionary.CreateBuilder<string, string>();
        var usedHintNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var consumer in consumers)
        {
            var names = PropertyNameResolver.ResolveConsumerPropertyNames(
                consumer.Dependencies,
                out _);
            result.Add(
                CreateHintName(consumer.FullyQualifiedName, usedHintNames),
                GenerateConsumerClass(
                    consumer,
                    dependency => names.TryGetValue(dependency.FullyQualifiedName, out var name)
                        ? name
                        : null));
        }

        return result.ToImmutable();
    }

    public static ImmutableDictionary<string, string> GenerateByIdentity(List<ConsumerModel> consumers)
    {
        if (consumers.Count == 0)
        {
            return ImmutableDictionary<string, string>.Empty;
        }

        var result = ImmutableDictionary.CreateBuilder<string, string>();
        var usedHintNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var consumer in consumers)
        {
            var names = PropertyNameResolver.ResolveConsumerPropertyNamesByIdentity(
                consumer.Dependencies,
                out _);
            result.Add(
                CreateHintName(consumer.FullyQualifiedName, usedHintNames),
                GenerateConsumerClass(
                    consumer,
                    dependency =>
                    {
                        var identity = dependency.Identity is { } dependencyIdentity &&
                                       !string.IsNullOrEmpty(dependencyIdentity.FullyQualifiedName)
                            ? dependencyIdentity
                            : new ServiceTypeIdentity(dependency.FullyQualifiedName, string.Empty);
                        return names.TryGetValue(identity, out var name)
                            ? name
                            : null;
                    }));
        }

        return result.ToImmutable();
    }

    private static string GenerateConsumerClass(
        ConsumerModel consumer,
        Func<ServiceReferenceModel, string?> resolvePropertyName)
    {
        var shape = consumer.Shape;
        var source = new StringBuilder();
        GeneratedSource.AppendLine(source, "// <auto-generated/>");

        var indentLevel = 0;
        var hasNamespace = !string.IsNullOrEmpty(shape.Namespace);

        // Both declaration shapes get the same nullable context. Without it the file-scoped path
        // analysed the generated members with nullable annotations disabled while the block-scoped
        // path enabled them, so the same consumer source produced a different result per shape and
        // any nullable annotation the emitter adds later would fail with CS8632 on one of them.
        GeneratedSource.AppendLine(source, "#nullable enable");
        GeneratedSource.AppendLine(source, string.Empty);
        if (shape.IsFileScoped)
        {
            if (hasNamespace)
            {
                GeneratedSource.AppendLine(source, $"namespace {shape.Namespace};");
            }

            GeneratedSource.AppendLine(source, string.Empty);
        }
        else if (hasNamespace)
        {
            GeneratedSource.AppendLine(source, $"namespace {shape.Namespace}");
            GeneratedSource.AppendLine(source, "{");
            indentLevel++;
        }

        foreach (var containingType in shape.ContainingTypes)
        {
            AppendTypeDeclaration(source, containingType, indentLevel);
            indentLevel++;
        }

        AppendTypeDeclaration(
            source,
            new ConsumerContainingTypeShape(
                shape.Name,
                shape.DeclarationKind,
                shape.Arity,
                shape.TypeParameters,
                shape.TypeParameterList,
                shape.ConstraintClauses,
                shape.IsPartial),
            indentLevel);
        indentLevel++;

        foreach (var dependency in consumer.Dependencies)
        {
            var propertyName = resolvePropertyName(dependency);
            if (propertyName is null ||
                consumer.ExistingMemberNames.Contains(propertyName))
            {
                continue;
            }

            var propertyAccessibility = GetPropertyAccessibility(shape, dependency);
            var dependencyType = ToGlobalTypeName(dependency.FullyQualifiedName);
            GeneratedSource.AppendLine(source, $"{Indent(indentLevel)}/// <summary>");
            GeneratedSource.AppendLine(source, $"{Indent(indentLevel)}/// Gets the singleton instance of {dependencyType}.");
            GeneratedSource.AppendLine(source, $"{Indent(indentLevel)}/// </summary>");
            GeneratedSource.AppendLine(source, $"{Indent(indentLevel)}{propertyAccessibility} static {dependencyType} {propertyName}");
            GeneratedSource.AppendLine(source, Indent(indentLevel) + "{");
            GeneratedSource.AppendLine(source, $"{Indent(indentLevel + 1)}get");
            GeneratedSource.AppendLine(source, Indent(indentLevel + 1) + "{");
            GeneratedSource.AppendLine(source, 
                $"{Indent(indentLevel + 2)}return global::SingletonDI.Generated.__SingletonDIHost__.Resolve<{dependencyType}>();");
            GeneratedSource.AppendLine(source, Indent(indentLevel + 1) + "}");
            GeneratedSource.AppendLine(source, Indent(indentLevel) + "}");
            GeneratedSource.AppendLine(source, string.Empty);
        }

        var closingIndentLevel = hasNamespace && !shape.IsFileScoped ? 1 : 0;
        for (var level = indentLevel - 1; level >= closingIndentLevel; level--)
        {
            GeneratedSource.AppendLine(source, Indent(level) + "}");
        }

        if (hasNamespace && !shape.IsFileScoped)
        {
            GeneratedSource.AppendLine(source, "}");
        }

        return source.ToString();
    }

    private static void AppendTypeDeclaration(
        StringBuilder source,
        ConsumerContainingTypeShape shape,
        int indentLevel)
    {
        GeneratedSource.AppendLine(source, 
            $"{Indent(indentLevel)}partial {GetDeclarationKeyword(shape.DeclarationKind)} {shape.Name}{shape.TypeParameterList}");
        if (!string.IsNullOrWhiteSpace(shape.ConstraintClauses))
        {
            foreach (var line in shape.ConstraintClauses.Split(
                         ['\r', '\n'],
                         StringSplitOptions.RemoveEmptyEntries))
            {
                GeneratedSource.AppendLine(source, $"{Indent(indentLevel + 1)}{line.Trim()}");
            }
        }

        GeneratedSource.AppendLine(source, Indent(indentLevel) + "{");
    }

    private static string GetDeclarationKeyword(ConsumerDeclarationKind kind)
    {
        return kind switch
        {
            ConsumerDeclarationKind.Struct => "struct",
            ConsumerDeclarationKind.RecordClass => "record class",
            ConsumerDeclarationKind.RecordStruct => "record struct",
            _ => "class",
        };
    }

    private static string GetPropertyAccessibility(
        ConsumerDeclarationShape shape,
        ServiceReferenceModel dependency)
    {
        // A static class cannot be inherited, and the language forbids a protected member in it, so it
        // belongs with the sealed shapes: the property is private.
        return shape.DeclarationKind is ConsumerDeclarationKind.Struct or ConsumerDeclarationKind.RecordStruct ||
               shape.IsSealed ||
               shape.IsStatic ||
               !dependency.CanUseProtectedProperty
            ? "private"
            : "protected";
    }

    private static string CreateHintName(string fullyQualifiedName, ISet<string> usedHintNames)
    {
        var identity = fullyQualifiedName.StartsWith("global::", StringComparison.Ordinal)
            ? fullyQualifiedName.Substring("global::".Length)
            : fullyQualifiedName;
        var sanitized = SanitizeHintName(identity);
        if (usedHintNames.Add(sanitized + ".g.cs"))
        {
            return sanitized + ".g.cs";
        }

        using var sha256 = SHA256.Create();
        var hash = BitConverter.ToString(sha256.ComputeHash(Encoding.UTF8.GetBytes(identity)))
            .Replace("-", string.Empty)
            .Substring(0, 8)
            .ToLowerInvariant();
        var candidate = $"{sanitized}_{hash}.g.cs";
        var suffix = 2;
        while (!usedHintNames.Add(candidate))
        {
            candidate = $"{sanitized}_{hash}_{suffix}.g.cs";
            suffix++;
        }

        return candidate;
    }

    private static string SanitizeHintName(string identity)
    {
        var characters = identity
            .Select(character =>
                character is >= 'a' and <= 'z' or >= 'A' and <= 'Z' or >= '0' and <= '9' or '_'
                    ? character
                    : '_')
            .ToArray();
        if (characters.Length == 0)
        {
            return "Consumer";
        }

        if (characters[0] is >= '0' and <= '9')
        {
            return "_" + new string(characters);
        }

        return new string(characters);
    }

    private static string Indent(int level)
    {
        return new string(' ', level * 4);
    }

    private static string ToGlobalTypeName(string fullyQualifiedName)
    {
        return fullyQualifiedName.StartsWith("global::", StringComparison.Ordinal)
            ? fullyQualifiedName
            : $"global::{fullyQualifiedName}";
    }
}
